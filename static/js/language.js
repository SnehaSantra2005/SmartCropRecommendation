    const originalTextNodes = new WeakMap();

    window.AgriSense = {
        getLanguage() {
            return localStorage.getItem("agrisense-language") || "en";
        },
        translate(key, language = this.getLanguage()) {
            if (language === "bn") return translations[key] || key;
            return key;
        },
        cropLabel(crop, language = this.getLanguage()) {
            const name = String(crop || "Unknown").toLowerCase();
            return language === "bn" ? (bnToEnCrops[name] || name) : name.charAt(0).toUpperCase() + name.slice(1);
        },
        speak(text) {
            if (!("speechSynthesis" in window)) return;
            window.speechSynthesis.cancel();
            const utterance = new SpeechSynthesisUtterance(text);
            utterance.lang = this.getLanguage() === "bn" ? "bn-IN" : "en-IN";
            utterance.rate = 0.9;
            const voices = window.speechSynthesis.getVoices();
            const voice = voices.find(v => v.lang.toLowerCase() === utterance.lang.toLowerCase())
                || voices.find(v => v.lang.toLowerCase().startsWith(utterance.lang.slice(0, 2)));
            if (voice) utterance.voice = voice;
            window.speechSynthesis.speak(utterance);
        },
        applyLanguage(language) {
            localStorage.setItem("agrisense-language", language);
            document.documentElement.lang = language === "bn" ? "bn" : "en";
            document.body.classList.toggle("bengali-mode", language === "bn");
            document.querySelectorAll("[data-i18n]").forEach(el => {
                const key = el.getAttribute("data-i18n");
                if (translations[key]) el.textContent = language === "bn" ? translations[key] : key;
            });
            // Translate exact static text nodes without replacing form controls or layout.
            const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
            const nodes = [];
            while (walker.nextNode()) nodes.push(walker.currentNode);
            nodes.forEach(node => {
                if (!originalTextNodes.has(node)) originalTextNodes.set(node, node.nodeValue);
                const original = originalTextNodes.get(node);
                const trimmed = original.trim();
                if (!trimmed) return;
                if (node.parentElement && node.parentElement.closest("[data-i18n],script,style,textarea,input,button.language-toggle")) return;
                if (translations[trimmed]) {
                    const leading = original.match(/^\s*/)?.[0] || "";
                    const trailing = original.match(/\s*$/)?.[0] || "";
                    node.nodeValue = leading + (language === "bn" ? translations[trimmed] : trimmed) + trailing;
                }
            });
            document.querySelectorAll("[placeholder]").forEach(el => {
                const original = el.dataset.placeholderEn || el.getAttribute("placeholder");
                if (!el.dataset.placeholderEn) el.dataset.placeholderEn = original;
                const bn = {
                    "e.g. 90": "যেমন ৯০", "e.g. 42": "যেমন ৪২", "e.g. 43": "যেমন ৪৩",
                    "e.g. 6.5": "যেমন ৬.৫", "e.g. 25": "যেমন ২৫", "e.g. 80": "যেমন ৮০",
                    "e.g. 200": "যেমন ২০০", "Search crop name...": "ফসলের নাম খুঁজুন..."
                };
                el.setAttribute("placeholder", language === "bn" ? (bn[original] || original) : original);
            });
            const toggle = document.getElementById("languageToggle");
            if (toggle) toggle.textContent = language === "bn" ? "English" : "বাংলা";
            document.dispatchEvent(new CustomEvent("agrisense:languagechange", { detail: { language } }));
        },
        initLanguageToggle() {
            const toggle = document.getElementById("languageToggle");
            if (toggle) toggle.addEventListener("click", () => this.applyLanguage(this.getLanguage() === "en" ? "bn" : "en"));
            this.applyLanguage(this.getLanguage());
        }
    };
    document.addEventListener("DOMContentLoaded", () => window.AgriSense.initLanguageToggle());
